"""Generates the ASGI app the attacker talks to, for automatic runs.

The generated module installs the plan's import hook, imports the user's
entrypoint, and registers it with the adapter's /invoke. It is rewritten for
every run inside the run folder; the user's project is never touched.
"""

from __future__ import annotations

from pathlib import Path

from agentguard.discovery.plan import InstrumentationPlan

TARGET_MODULE = "agentguard_target"

TEMPLATE = '''"""Generated by AgentGuard for one run. Rewritten on every run; do not edit."""
import importlib
import sys

# A project folder named `agentguard` (for example a clone) must never shadow the real package.
sys.path.insert(0, {package_parent!r})  # must run before the first import of agentguard

from agentguard.adapter import app, expose
from agentguard.instrument.hook import install

install({plan_path!r}, {project_root!r})
_module = importlib.import_module({entry_module!r})
expose(getattr(_module, {entry_name!r}))
'''


def write_target(run_dir: Path, plan: InstrumentationPlan, project_root: Path) -> Path:
    entry = plan.entrypoint
    if entry is None:
        raise ValueError("the plan has no included entrypoint")
    run_dir.mkdir(parents=True, exist_ok=True)
    import agentguard as _pkg
    source = TEMPLATE.format(
        package_parent=str(Path(_pkg.__file__).resolve().parents[1]),
        plan_path=str(run_dir / "plan.json"),
        project_root=str(Path(project_root).resolve()),
        entry_module=entry.module,
        entry_name=entry.name,
    )
    path = run_dir / f"{TARGET_MODULE}.py"
    path.write_text(source, encoding="utf-8")
    return path
